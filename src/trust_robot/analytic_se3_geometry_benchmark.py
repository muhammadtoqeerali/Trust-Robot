"""Development-only analytic SE(3) LiDAR odometry benchmark.

The analytic reference is generated by the fixture and is supplied
only to the scoring stage, never to the registration/odometry
estimator. It is not an independent measured ground-truth source.

No physical sensor, calibration, synchronization, health model,
factor weighting or held-out scientific evaluation is involved.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import math
import signal
import sys
from pathlib import Path

import numpy as np
import scipy
from scipy.spatial.transform import Rotation

from trust_robot.clean_backbone import (
    CleanBackboneConfig,
    FixedCleanBackbone,
    PoseSE3,
    RelativePoseIncrement,
)
from trust_robot.lidar_frontend import (
    register_current_scan_to_previous,
)
from trust_robot.diagnostics import (
    extract_lidar_registration_diagnostics,
)

SCHEMA = "TRUST_ROBOT_ANALYTIC_SE3_GEOMETRY_BENCHMARK_V1"
SEED = 20261012
FRAMES = 20
POINTS = 96
CONDITIONS = ("clean", "sparse", "noise", "offset")
NOISE_SIGMA_M = 0.035
OFFSET_XYZ_M = (0.12, -0.05, 0.04)
PERTURBATION_START = 5
PERTURBATION_END = 14

FEATURE_NAMES = (
    "source_point_count",
    "target_point_count",
    "fixed_point_iterations",
    "final_correspondence_count",
    "final_nearest_neighbor_rmse_m",
)

BODY_FRAME = "ANALYTIC_SYNTHETIC_LIDAR"
ODOM_FRAME = "ARBITRARY_ANALYTIC_ODOMETRY"
SOURCE_ID = "FROZEN_PHASE2_EXACT_NN"


def canonical(value):
    return (
        json.dumps(
            value,
            sort_keys=True,
            separators=(",", ":"),
            allow_nan=False,
        ) + "\n"
    ).encode("utf-8")


def quaternion_wxyz(rotation):
    x, y, z, w = rotation.as_quat()
    return (float(w), float(x), float(y), float(z))


def rotation_from_wxyz(values):
    w, x, y, z = values
    return Rotation.from_quat([x, y, z, w])


def analytic_pose(index):
    """Known six-axis synthetic trajectory; not a measured reference."""
    k = float(index)

    translation = np.array([
        0.030 * k,
        0.050 * math.sin(0.11 * k),
        0.040 * math.sin(0.17 * k),
    ], dtype=np.float64)

    rotation = Rotation.from_euler(
        "xyz",
        [
            0.025 * math.sin(0.13 * k),
            0.020 * math.sin(0.09 * k),
            0.007 * k,
        ],
    )

    return translation, rotation


def make_fixture():
    """Build ideal full-overlap static-landmark LiDAR observations."""
    rng = np.random.default_rng(SEED)

    landmarks = rng.uniform(
        -4.0, 4.0, size=(POINTS, 3)
    ).astype(np.float64)

    landmarks[:, 2] += 1.0

    if np.linalg.matrix_rank(
        landmarks - landmarks.mean(axis=0)
    ) != 3:
        raise ValueError("Fixture landmarks are degenerate")

    reference = [analytic_pose(k) for k in range(FRAMES)]

    # Each cloud is expressed in its synthetic sensor frame.
    # Row-vector form: sensor_xyz = (world_xyz - t) @ R.
    original = [
        np.ascontiguousarray(
            (landmarks - t) @ rot.as_matrix(),
            dtype=np.float64,
        )
        for t, rot in reference
    ]

    lanes = {}

    for condition in CONDITIONS:
        clouds = [cloud.copy() for cloud in original]

        for k in range(PERTURBATION_START, PERTURBATION_END):
            if condition == "sparse":
                clouds[k] = clouds[k][::3].copy()

            elif condition == "noise":
                noise = np.random.default_rng(
                    SEED + 1000 + k
                ).normal(
                    loc=0.0,
                    scale=NOISE_SIGMA_M,
                    size=clouds[k].shape,
                )
                clouds[k] = clouds[k] + noise

            elif condition == "offset":
                clouds[k] = clouds[k] + np.asarray(
                    OFFSET_XYZ_M,
                    dtype=np.float64,
                )

        lanes[condition] = clouds

    return lanes, reference, landmarks


def register_bounded(previous, current, seconds=3.0):
    """Execute the unchanged frozen Phase-2 registration frontend."""
    if seconds <= 0:
        raise ValueError("Invalid registration budget")

    def timed_out(_signum, _frame):
        raise TimeoutError("Registration exceeded time budget")

    old = signal.signal(signal.SIGALRM, timed_out)
    signal.setitimer(signal.ITIMER_REAL, seconds)

    try:
        return register_current_scan_to_previous(
            previous, current
        )
    finally:
        signal.setitimer(signal.ITIMER_REAL, 0.0)
        signal.signal(signal.SIGALRM, old)


def estimate(clouds):
    """Estimator input is scans ONLY; no reference poses."""
    if len(clouds) < 2:
        raise ValueError("Need at least two scans")

    config = CleanBackboneConfig(
        world_frame_id=ODOM_FRAME,
        body_frame_id=BODY_FRAME,
        relative_pose_source_id=SOURCE_ID,
        initial_timestamp_ns=0,
        initial_pose_world_T_body=PoseSE3.identity(),
    )

    backbone = FixedCleanBackbone(config)

    output = [{
        "sample_index": 0,
        "status": "ARBITRARY_INITIAL_POSE",
        "pose": backbone.state.pose_world_T_body.to_dict(),
        "registration_features": None,
        "synthetic_time_ns": 0,
    }]

    for k in range(1, len(clouds)):
        result = register_bounded(
            clouds[k-1], clouds[k]
        )

        diagnostic = extract_lidar_registration_diagnostics(
            result.diagnostics
        )

        features = {
            item.name: item.value
            for item in diagnostic.features
        }

        if tuple(features) != FEATURE_NAMES:
            raise ValueError("Frozen Phase-4 feature order changed")

        increment = RelativePoseIncrement(
            timestamp_ns=k * 100_000_000,
            body_frame_id=BODY_FRAME,
            source_id=SOURCE_ID,
            delta_prev_body_T_current_body=(
                result.previous_lidar_T_current_lidar
            ),
        )

        state = backbone.apply(increment)

        output.append({
            "sample_index": k,
            "status": "ESTIMATED_FROM_FROZEN_SCAN_REGISTRATION",
            "pose": state.pose_world_T_body.to_dict(),
            "registration_features": features,
            "synthetic_time_ns": k * 100_000_000,
        })

    return output


def evaluate(estimates, reference):
    """Compare estimated poses to manufactured fixture truth only."""
    if len(estimates) != len(reference):
        raise ValueError("Reference/estimate length mismatch")

    translation_errors = []
    rotation_errors_deg = []

    for record, (truth_t, truth_r) in zip(
        estimates, reference, strict=True
    ):
        pose = record["pose"]
        estimated_t = np.asarray(
            pose["translation_m"], dtype=np.float64
        )
        estimated_r = rotation_from_wxyz(
            pose["quaternion_wxyz"]
        )

        translation_errors.append(
            float(np.linalg.norm(estimated_t - truth_t))
        )
        rotation_errors_deg.append(
            float(
                (estimated_r.inv() * truth_r).magnitude()
                * 180.0 / math.pi
            )
        )

    te = np.asarray(translation_errors, dtype=np.float64)
    re = np.asarray(rotation_errors_deg, dtype=np.float64)

    if not (np.isfinite(te).all() and np.isfinite(re).all()):
        raise ValueError("Nonfinite fixture errors")

    return {
        "fixture_translation_rmse_m": float(
            np.sqrt(np.mean(te * te))
        ),
        "fixture_rotation_rmse_deg": float(
            np.sqrt(np.mean(re * re))
        ),
        "fixture_translation_max_m": float(np.max(te)),
        "fixture_rotation_max_deg": float(np.max(re)),
        "fixture_translation_final_m": float(te[-1]),
        "fixture_rotation_final_deg": float(re[-1]),
        "analytic_reference_only": True,
        "independent_measured_reference": False,
        "scientific_dataset_ate_rpe": False,
    }


def execute():
    scans, reference, landmarks = make_fixture()

    results = {}
    outputs = {}

    for condition in CONDITIONS:
        trajectory = estimate(scans[condition])
        metrics = evaluate(trajectory, reference)

        if len(trajectory) != FRAMES:
            raise ValueError("Incomplete synthetic pose trajectory")

        output = b"".join(canonical(x) for x in trajectory)

        outputs[f"{condition}_estimated_poses.jsonl"] = output
        results[condition] = metrics

    if not (
        results["clean"]["fixture_translation_rmse_m"] < 1e-6
        and results["clean"]["fixture_rotation_rmse_deg"] < 1e-6
    ):
        raise ValueError("Ideal analytic fixture regression failed")

    for condition in ("sparse", "noise", "offset"):
        if not (
            results[condition]["fixture_translation_rmse_m"]
            > results["clean"]["fixture_translation_rmse_m"] + 1e-5
        ):
            raise ValueError(
                f"Expected fixture translation perturbation not observed: "
                f"{condition}"
            )

    manifest = {
        "schema": SCHEMA,
        "status": "DEVELOPMENT_ONLY_ANALYTIC_FIXTURE_PASSED",
        "fixture_seed": SEED,
        "fixture_frames": FRAMES,
        "static_landmark_count": len(landmarks),
        "landmark_spatial_rank": int(np.linalg.matrix_rank(
            landmarks - landmarks.mean(axis=0)
        )),
        "conditions": list(CONDITIONS),
        "perturbation_index_window": [
            PERTURBATION_START,
            PERTURBATION_END,
        ],
        "sparsity_keep_every_nth": 3,
        "noise_sigma_m": NOISE_SIGMA_M,
        "coordinate_offset_xyz_m": list(OFFSET_XYZ_M),
        "numeric_environment": {
            "python": sys.version.split()[0],
            "numpy": np.__version__,
            "scipy": scipy.__version__,
        },
        "metrics_by_condition": results,
        "estimated_pose_count_per_condition": FRAMES,
        "frozen_phase2_registration_reused": True,
        "frozen_phase4_diagnostics_reused": True,
        "fixed_clean_backbone_reused": True,
        "reference_passed_to_estimator": False,
        "reference_origin": "ANALYTIC_FIXTURE_GENERATOR",
        "real_independent_ground_truth": False,
        "full_sensor_physics_simulated": False,
        "realistic_lidar_visibility_model": False,
        "capture_timing_calibrated": False,
        "sensor_extrinsics_calibrated": False,
        "held_out_dataset_evaluation": False,
        "health_labels_generated": False,
        "health_model_trained": False,
        "factor_conditioning_executed": False,
        "fixed_lag_optimizer_executed": False,
        "physical_robot_contacted": False,
        "output_sha256": {
            name: hashlib.sha256(blob).hexdigest()
            for name, blob in sorted(outputs.items())
        },
    }

    return outputs, manifest


def run(destination):
    if destination.exists() or destination.is_symlink():
        raise ValueError("Benchmark destination exists")

    if (
        not destination.parent.is_dir()
        or destination.parent.is_symlink()
    ):
        raise ValueError("Unsafe benchmark output parent")

    first_outputs, first_manifest = execute()
    again_outputs, again_manifest = execute()

    if first_outputs != again_outputs:
        raise ValueError("Non-deterministic analytic pose results")
    if first_manifest != again_manifest:
        raise ValueError("Non-deterministic analytic manifest")

    first_manifest["repeated_derivation_identical"] = True

    destination.mkdir(mode=0o700)

    for name, blob in sorted(first_outputs.items()):
        (destination / name).write_bytes(blob)

    (destination / "benchmark_manifest_v1.json").write_text(
        json.dumps(first_manifest, sort_keys=True, indent=2) + "\n"
    )

    return first_manifest


def main():
    p = argparse.ArgumentParser()
    p.add_argument("destination", type=Path)
    args = p.parse_args()

    result = run(args.destination)

    print("ANALYTIC_POSES_PER_CONDITION=", FRAMES)
    print("STATIC_3D_LANDMARKS=", POINTS)
    print("PAIRED_CONDITIONS=", ",".join(CONDITIONS))

    for condition in CONDITIONS:
        metrics = result["metrics_by_condition"][condition]
        print(
            condition.upper() + "_TRANSLATION_RMSE_M=",
            round(metrics["fixture_translation_rmse_m"], 8)
        )
        print(
            condition.upper() + "_ROTATION_RMSE_DEG=",
            round(metrics["fixture_rotation_rmse_deg"], 8)
        )

    print("REFERENCE_NOT_PASSED_TO_ESTIMATOR=PASS")
    print("DETERMINISTIC_DOUBLE_DERIVATION=PASS")
    print("PHYSICAL_GROUND_TRUTH=NOT_ESTABLISHED")
    print("ANALYTIC_SE3_GEOMETRY_BENCHMARK=PASS")


if __name__ == "__main__":
    main()
