"""Five-node synthetic-only 15D factor-slot integration.

Reuses the published Schur-marginalized estimator and
its factor_factory interface without changing solver code.

The camera-labeled packet is copied from an analytic LiDAR
relative-pose factor. It is not a camera measurement or
independent evidence, and cannot support a sensor recovery
or physical robustness claim.

No recorded input, health inference, factor weighting,
covariance calibration, real labels or GT scoring.
"""
from __future__ import annotations

import hashlib
import json

from trust_robot.analytic_inertial_15d import make_fixture
from trust_robot.analytic_preintegrated_fusion import (
    NODE_FRAMES,
    make_factors,
)
from trust_robot.analytic_marginalized_fusion import (
    estimate_marginalized,
)
from trust_robot.multimodal_factor_interface import (
    ANALYTIC_FRAME,
    CAMERA_SOURCE,
    SyntheticPoseFactor,
    assemble_synthetic_pose_slot,
)

SCHEMA = (
    "TRUST_ROBOT_R135_A6_ANALYTIC_15D_POSE_SLOT_INTEGRATION_V1"
)

STATUS = "UNTRUSTED_SYNTHETIC_SOLVER_DIAGNOSTIC_ONLY"

SCENARIOS = (
    "baseline",
    "lidar_edge_removed",
    "camera_substitutes_lidar",
    "camera_on_removed_lidar_edge",
)

EDGE = (1, 2)

EXPECTED_LIDAR_EDGES = frozenset((
    (0, 1),
    (0, 2),
    (1, 2),
    (1, 3),
    (2, 3),
    (2, 4),
    (3, 4),
))

EXPECTED_IMU_EDGES = frozenset((
    (0, 1),
    (1, 2),
    (2, 3),
    (3, 4),
))


class Synthetic15DIntegrationError(ValueError):
    """Invalid or inconsistent analytic factor intervention."""


def _digest(payload):
    return hashlib.sha256(
        json.dumps(
            payload,
            sort_keys=True,
            separators=(",", ":"),
            allow_nan=False,
        ).encode("utf-8")
    ).hexdigest()


def _select(name, baseline):
    lidar = dict(baseline)

    removed = name in (
        "lidar_edge_removed",
        "camera_on_removed_lidar_edge",
    )

    camera = name in (
        "camera_substitutes_lidar",
        "camera_on_removed_lidar_edge",
    )

    # The surrogate is copied from the original synthetic
    # LiDAR factor. This supplies NO independent camera evidence.
    source_measurement = baseline[EDGE]

    if removed:
        del lidar[EDGE]

    packets = []

    if camera:
        packets.append(
            SyntheticPoseFactor(
                modality="camera",
                edge=EDGE,
                measurement_id=(
                    "r135-a6-copied-analytic-factor-1-2"
                ),
                source_id=CAMERA_SOURCE,
                frame_id=ANALYTIC_FRAME,
                measurement=source_measurement,
            )
        )

    merged, ledger = assemble_synthetic_pose_slot(
        lidar,
        packets,
        NODE_FRAMES,
    )

    expected = (
        EXPECTED_LIDAR_EDGES - {EDGE}
        if name == "lidar_edge_removed"
        else EXPECTED_LIDAR_EDGES
    )

    if set(merged) != expected:
        raise Synthetic15DIntegrationError(
            "Unexpected synthetic graph topology"
        )

    if (
        ledger["same_edge_measurements_double_counted"] is not False
        or ledger["backend_can_independently_weight_camera"] is not False
        or ledger["real_sensor_factor_execution_authorized"] is not False
        or ledger["real_visual_frontend_used"] is not False
    ):
        raise Synthetic15DIntegrationError(
            "Factor-admission boundary changed"
        )

    if camera and merged[EDGE] != source_measurement:
        raise Synthetic15DIntegrationError(
            "Surrogate did not preserve analytic factor value"
        )

    return merged, ledger, len(lidar), len(packets)


def run_scenario(name):
    """Execute one internally generated analytic 15D scenario.

    The public API accepts only the frozen scenario name.
    External fixtures, sensor records, packets, health
    probabilities and factor weights cannot be supplied.
    """
    if type(name) is not str or name not in SCENARIOS:
        raise Synthetic15DIntegrationError(
            "Unexpected analytic intervention scenario"
        )

    if NODE_FRAMES != (0, 2, 4, 6, 8):
        raise Synthetic15DIntegrationError(
            "Frozen estimator node chronology changed"
        )

    fixture, synthetic_reference = make_fixture("clean")

    # Synthetic fixture truth is generated by the existing
    # factory but is never used for estimation or scoring.
    del synthetic_reference

    captured = []

    def factor_factory(internal_fixture):
        if internal_fixture is not fixture or captured:
            raise Synthetic15DIntegrationError(
                "Unexpected factor-factory invocation"
            )

        inertial, baseline, source_counts = make_factors(
            internal_fixture
        )

        if (
            set(inertial) != EXPECTED_IMU_EDGES
            or set(baseline) != EXPECTED_LIDAR_EDGES
            or source_counts["imu_intervals"] != 4
            or source_counts["lidar_factor_count"] != 7
            or source_counts["imu_samples_reused"] is not False
        ):
            raise Synthetic15DIntegrationError(
                "Frozen analytic factor topology changed"
            )

        merged, ledger, lidar_inputs, camera_inputs = (
            _select(name, baseline)
        )

        metadata = dict(source_counts)

        # In the legacy backend this historical key counts
        # graph pose slots, even when a synthetic camera-labeled
        # surrogate occupies one such slot.
        metadata["lidar_factor_count"] = len(merged)

        metadata.update({
            "original_analytic_lidar_factor_count": 7,
            "selected_analytic_lidar_factor_count":
                ledger["synthetic_lidar_factor_count"],
            "camera_labeled_surrogate_slot_count":
                ledger["synthetic_camera_factor_count"],
            "camera_surrogate_copied_from_analytic_lidar": True,
            "independent_camera_evidence_available": False,
            "independent_camera_weighting_authorized": False,
            "real_sensor_factor_execution_authorized": False,
        })

        captured.append((
            ledger,
            lidar_inputs,
            camera_inputs,
            len(merged),
        ))

        return inertial, merged, metadata

    records, audit = estimate_marginalized(
        fixture,
        node_frames=NODE_FRAMES,
        factor_factory=factor_factory,
    )

    if len(captured) != 1:
        raise Synthetic15DIntegrationError(
            "Factor factory was not called exactly once"
        )

    ledger, lidar_inputs, camera_inputs, pose_slots = (
        captured[0]
    )

    if (
        len(records) != 5
        or audit["accepted_window_count"] != 4
        or audit["schur_elimination_count"] != 3
        or audit["unaccounted_factor_count"] != 0
        or audit["factor_reuse_after_marginalization"] is not False
        or audit["imu_samples_reused"] is not False
        or audit["lidar_factor_count"] != pose_slots
    ):
        raise Synthetic15DIntegrationError(
            "15D estimator factor accounting failed"
        )

    for record in records:
        if (
            record["state_dimension"] != 15
            or record["reference_pose"] is not None
        ):
            raise Synthetic15DIntegrationError(
                "Invalid synthetic estimator record"
            )

    if any(
        window["jacobian_rank"] != window["required_rank"]
        or window["accepted"] is not True
        for window in audit["windows"]
    ):
        raise Synthetic15DIntegrationError(
            "Unaccepted analytic optimizer window"
        )

    # SHA256 summarizes the manufactured solver state outputs.
    # It does not constitute GT validation or physical accuracy.
    state_digest = _digest(records)

    return {
        "schema": SCHEMA,
        "status": STATUS,
        "scenario": name,
        "state_dimension": 15,
        "node_count": len(records),
        "synthetic_imu_factor_count": 4,
        "original_analytic_lidar_factor_count": 7,
        "synthetic_lidar_input_factor_count": lidar_inputs,
        "synthetic_camera_surrogate_input_count": camera_inputs,
        "selected_lidar_slot_count":
            ledger["synthetic_lidar_factor_count"],
        "selected_camera_surrogate_slot_count":
            ledger["synthetic_camera_factor_count"],
        "total_pose_slot_count": pose_slots,
        "factor_ledger": ledger["factor_ledger"],
        "replaced_lidar_edges": ledger["replaced_lidar_edges"],
        "accepted_window_count": audit["accepted_window_count"],
        "schur_elimination_count":
            audit["schur_elimination_count"],
        "unaccounted_factor_count":
            audit["unaccounted_factor_count"],
        "factor_reuse_after_marginalization":
            audit["factor_reuse_after_marginalization"],
        "imu_samples_reused": audit["imu_samples_reused"],
        "all_windows_numerically_full_rank": True,
        "synthetic_state_content_sha256": state_digest,
        "camera_surrogate_copied_from_analytic_lidar": True,
        "independent_camera_evidence_available": False,
        "independent_camera_weighting_authorized": False,
        "physical_observability_proven": False,
        "posterior_consistency_proven": False,
        "physical_sensor_calibration_validated": False,
        "health_probabilities_generated": False,
        "health_labels_assigned": False,
        "factor_weights_modified": False,
        "recorded_ground_truth_accessed": False,
        "recorded_sensor_data_used": False,
        "localization_recovery_demonstrated": False,
        "real_factor_execution_authorized": False,
        "confirmation_test_accessed": False,
    }


def run_all_scenarios():
    return tuple(
        run_scenario(name)
        for name in SCENARIOS
    )
