"""Three-modality manufactured input to existing 15D nonlinear estimator.

Camera-style relative poses are generated by a simulator from
manufactured trajectory truth with seeded perturbations.

LiDAR poses come from the existing registration frontend.
IMU information uses existing preintegrated factors.

The estimator itself receives synthetic measurements, not
reference trajectory states. No actual image motion frontend
or real cross-modal synchronization is tested.
"""
from __future__ import annotations

import hashlib
import json

import numpy as np
from scipy.spatial.transform import Rotation

from trust_robot.clean_backbone import PoseSE3
from trust_robot.analytic_inertial_15d import (
    as_pose,
    make_fixture,
)
from trust_robot.analytic_preintegrated_fusion import (
    NODE_FRAMES,
    make_factors,
)
from trust_robot.analytic_marginalized_fusion import (
    estimate_marginalized,
)
from trust_robot.multimodal_factor_interface import (
    ANALYTIC_FRAME,
    CAMERA_SOURCE,
    SyntheticPoseFactor,
    assemble_synthetic_pose_slot,
)

SCHEMA = "TRUST_ROBOT_ANALYTIC_THREE_MODALITY_BRIDGE_DEV_V1"

CAMERA_EDGES = ((0, 1), (2, 3))
SEEDS = (13, 31, 71)


def manufactured_camera_packets(truth, *, seed):
    """Manufacture relative body-motion measurements, not image VO."""
    if type(seed) is not int or seed < 0:
        raise ValueError("Invalid synthetic camera seed")

    if len(truth) != NODE_FRAMES[-1] + 1:
        raise ValueError("Invalid simulator truth length")

    rng = np.random.default_rng(seed)
    packets = []

    for i, j in CAMERA_EDGES:
        a = as_pose(truth[NODE_FRAMES[i]])
        b = as_pose(truth[NODE_FRAMES[j]])

        base = a.inverse().compose(b)

        position_noise = rng.normal(0, 0.003, 3)
        rotation_noise = rng.normal(0, 0.001, 3)

        q = base.quaternion_wxyz
        orientation = Rotation.from_quat(
            [q[1], q[2], q[3], q[0]]
        ) * Rotation.from_rotvec(rotation_noise)

        qx, qy, qz, qw = orientation.as_quat()

        measured = PoseSE3(
            translation_m=tuple(
                float(v)
                for v in (
                    np.asarray(base.translation_m)
                    + position_noise
                )
            ),
            quaternion_wxyz=(
                float(qw), float(qx), float(qy), float(qz)
            ),
        )

        packets.append(SyntheticPoseFactor(
            modality="camera",
            edge=(i, j),
            measurement_id=f"camera_sim_seed{seed}:{i}:{j}",
            source_id=CAMERA_SOURCE,
            frame_id=ANALYTIC_FRAME,
            measurement=measured,
        ))

    return tuple(packets)


def execute_case(condition, seed, *, camera_enabled=True):
    """Run the actual 15D solver on an explicit synthetic factor mix."""
    if condition not in ("clean", "lidar_dropout"):
        raise ValueError("Invalid manufactured experiment condition")

    if type(camera_enabled) is not bool:
        raise ValueError("Invalid camera enabled flag")

    fixture, simulator_truth = make_fixture(condition)

    # Truth is used ONLY to create manufactured observations.
    # It is not passed as a state or reference argument to the solver.
    camera = (
        manufactured_camera_packets(simulator_truth, seed=seed)
        if camera_enabled else ()
    )

    factory_metadata = {}

    def synthetic_factor_factory(sensor_fixture):
        inertial, lidar, counts = make_factors(sensor_fixture)

        combined, pose_info = assemble_synthetic_pose_slot(
            lidar, camera, NODE_FRAMES
        )

        factory_metadata.update(pose_info)

        return inertial, combined, {
            **counts,
            "synthetic_camera_motion_factors":
                pose_info["synthetic_camera_factor_count"],
            "synthetic_lidar_registration_factors":
                pose_info["synthetic_lidar_factor_count"],
            "backend_relative_pose_factor_count":
                pose_info["total_relative_pose_factor_count"],
            "legacy_pose_slot_is_modality_agnostic": True,
        }

    estimated, raw_audit = estimate_marginalized(
        fixture,
        node_frames=NODE_FRAMES,
        factor_factory=synthetic_factor_factory,
    )

    if (
        len(estimated) != len(NODE_FRAMES)
        or raw_audit["accepted_window_count"]
           != len(NODE_FRAMES)-1
        or raw_audit["unaccounted_factor_count"] != 0
        or raw_audit["factor_reuse_after_marginalization"]
           is not False
    ):
        raise ValueError(
            "Nonlinear synthetic factor integration failed"
        )

    if not factory_metadata:
        raise ValueError("Missing modality factor ledger")

    # The backend historically calls every relative-pose factor
    # 'lidar'. Do not export those mislabelled per-window fields
    # as a modality-specific scientific measurement count.
    windows = [
        {
            "end_node": row["end_node"],
            "accepted": row["accepted"],
            "active_relative_pose_factors": row[
                "active_lidar_factor_count"
            ],
            "active_preintegrated_imu_factors": row[
                "active_imu_factor_count"
            ],
        }
        for row in raw_audit["windows"]
    ]

    states_blob = (
        json.dumps(
            estimated, sort_keys=True,
            separators=(",", ":"), allow_nan=False,
        ) + "\n"
    ).encode("utf-8")

    return {
        "schema": SCHEMA,
        "condition": condition,
        "seed": seed,
        "camera_enabled": camera_enabled,
        "estimated_node_count": len(estimated),
        "estimated_trajectory_sha256": hashlib.sha256(
            states_blob
        ).hexdigest(),
        "relative_pose_factors": factory_metadata,
        "inertial_factor_count": raw_audit["imu_intervals"],
        "accepted_window_count":
            raw_audit["accepted_window_count"],
        "schur_elimination_count":
            raw_audit["schur_elimination_count"],
        "windows": windows,
        "factor_accounting_valid": True,
        "camera_source": (
            "MANUFACTURED_FROM_SYNTHETIC_TRAJECTORY"
            if camera_enabled else "DISABLED"
        ),
        "lidar_source": "ANALYTIC_LIDAR_REGISTRATION",
        "imu_source": "ANALYTIC_IMU_PREINTEGRATION",
        "camera_pixels_processed": False,
        "camera_motion_independently_measured": False,
        "reference_poses_passed_to_estimator": False,
        "real_sensor_data_used": False,
        "physical_synchronization_verified": False,
        "camera_extrinsics_verified": False,
        "independent_ground_truth_scored": False,
        "factor_covariance_empirically_calibrated": False,
        "health_factor_weighting_executed": False,
    }


def execute():
    cases = [
        execute_case(condition, seed, camera_enabled=enabled)
        for condition in ("clean", "lidar_dropout")
        for seed in SEEDS
        for enabled in (False, True)
    ]

    if len(cases) != 12:
        raise ValueError("Incomplete development scenarios")

    for case in cases:
        factors = case["relative_pose_factors"]

        if case["camera_enabled"]:
            if factors["synthetic_camera_factor_count"] != 2:
                raise ValueError(
                    "Missing manufactured camera constraints"
                )
        else:
            if factors["synthetic_camera_factor_count"] != 0:
                raise ValueError(
                    "Camera factors unexpectedly present"
                )

        if (
            factors["same_edge_measurements_double_counted"]
            or case["accepted_window_count"] != 4
            or case["schur_elimination_count"] != 3
        ):
            raise ValueError("Estimator factor chronology invalid")

    return {
        "schema": SCHEMA,
        "status": "SYNTHETIC_THREE_MODALITY_INTERFACE_VALIDATED",
        "case_count": len(cases),
        "cases": cases,
        "real_three_modality_localization_verified": False,
        "physical_sensor_factor_execution_authorized": False,
        "camera_motion_frontend_implemented": False,
        "legacy_estimator_modified": False,
        "frozen_scientific_gates_changed": False,
    }


def canonical(value):
    return (
        json.dumps(
            value,
            sort_keys=True,
            separators=(",", ":"),
            allow_nan=False,
        ) + "\n"
    ).encode("utf-8")
